// gitfree_build_identity_test.go — the D5 contract: every installed
// executable must report a TRUSTWORTHY embedded build identity, and the
// identity must survive a build that had no Git metadata to read.
//
// THE CONTRACT (decision D5)
//
// MPM is migrating from a Git checkout to versioned, Git-free runtime
// bundles. Two properties have to hold at once:
//
//  1. The INSTALLED binary reports its identity without needing a .git
//     directory. It never did — the provenance is stamped at link time
//     — but the migration makes it load-bearing: the final installation
//     has no Git metadata anywhere near it.
//
//  2. The identity is TRUSTWORTHY. A binary built from a Git-free
//     source export used to report commit "unknown", because there was
//     no history to ask. "unknown" is honest but useless: an operator
//     cannot tell which build they are running, and a rollback target
//     cannot be named.
//
// The mechanism is scripts/build-provenance.sh's MPM_BUILD_COMMIT and
// MPM_BUILD_DIRTY overrides: the producer STATES the revision it
// exported, and the build stamps that. The statement is validated —
// malformed or contradictory assertions are refused — so the identity
// is asserted, never guessed.
//
// WHAT THIS TEST PROVES
//
// It builds the five binaries from a Git-free COPY of the source tree,
// with the producer's assertion, and asserts that every one of them
// reports that commit — the same commit, not five different ones.
//
// It also asserts the NEGATIVE: without the assertion, the same
// Git-free tree reports "unknown". Without that assertion the test
// would pass for the wrong reason: a binary that happens to have been
// built somewhere else.

package release_acceptance_test

import (
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// repoRoot is the repository root, one level above this module.
const repoRoot = ".."

// theCommit is the revision the test asserts was embedded.
//
// It is a REAL commit — the accepted release candidate's — rather than a
// synthetic hex string, so the assertion is the same shape a release
// builder would make: a revision an operator could actually look up.
const theCommit = "4111c46dbe30de44e9ed8f7a715fff9e8c3e469e"

// gitFreeCopy copies the source tree to dst WITHOUT any Git metadata.
//
// It is a copy rather than a `git archive` because the test must build
// the WORKING tree — the tree under test, with the changes that are
// not committed yet — and a committed archive would not contain them.
//
// The exclusion list is explicit: .git is the point, and the other
// entries are build outputs and vendored trees that are large, are
// regenerated by the build, and are not source.
func gitFreeCopy(t *testing.T, dst string) {
	t.Helper()
	cmd := exec.Command("tar",
		"--exclude=./.git",
		"--exclude=./.build",
		"--exclude=./node_modules",
		"--exclude=./agent_installation/mpm-opencode/node_modules",
		"-cf", "-", ".")
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("tar the source tree: %v", err)
	}
	extract := exec.Command("tar", "-xf", "-", "-C", dst)
	extract.Stdin = strings.NewReader(string(out))
	if err := extract.Run(); err != nil {
		t.Fatalf("extract the source tree: %v", err)
	}
	// The copy must genuinely have no Git metadata.
	if _, err := os.Stat(filepath.Join(dst, ".git")); err == nil {
		t.Fatal("the copy still has a .git directory")
	}
}

// buildFromGitFreeTree builds the five release binaries from a
// Git-free copy of the source tree, with the producer's provenance
// assertion.
//
// It returns the directory the binaries were written to.
func buildFromGitFreeTree(t *testing.T, tree string, commit, dirty string) string {
	t.Helper()
	binDir := filepath.Join(tree, "gitfree-bin")
	if err := os.MkdirAll(binDir, 0o755); err != nil {
		t.Fatalf("mkdir %s: %v", binDir, err)
	}

	// The provenance payload comes from the SAME script the canonical
	// build uses, so the test exercises the real convention rather
	// than a hand-written -ldflags string.
	prov := exec.Command(filepath.Join(tree, "scripts", "build-provenance.sh"), "ldflags")
	prov.Dir = tree
	prov.Env = append(os.Environ(),
		"MPM_BUILD_COMMIT="+commit,
		"MPM_BUILD_DIRTY="+dirty,
		"SOURCE_DATE_EPOCH=1700000000",
	)
	ldflags, err := prov.Output()
	if err != nil {
		t.Fatalf("build-provenance.sh: %v", err)
	}
	if !strings.Contains(string(ldflags), commit) {
		t.Fatalf("the ldflags payload does not carry the asserted commit: %s", ldflags)
	}

	args := []string{"build", "-tags", "fts5", "-ldflags", strings.TrimSpace(string(ldflags)), "-o", binDir}
	for _, pkg := range []string{
		"./cmd/mpm",
		"./cmd/mpm-mcp",
		"./cmd/mpm-scheduler",
		"./cmd/mpm-critic",
		"./cmd/mpm-telemetry",
	} {
		args = append(args, pkg)
	}
	cmd := exec.Command("go", args...)
	cmd.Dir = tree
	cmd.Env = os.Environ()
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go build from the Git-free tree: %v\n%s", err, out)
	}
	return binDir
}

// identityOf runs `<binary> --version` and returns the reported
// product version, commit and dirty state.
//
// The human form is parsed for every binary, because it is the
// OPERATOR's surface — it is what `mpm --version` prints — and the
// binaries do not agree on which flag carries the machine-readable
// form.
func identityOf(t *testing.T, bin string) (version, commit, dirty string) {
	t.Helper()
	out, err := exec.Command(bin, "--version").CombinedOutput()
	if err != nil {
		t.Fatalf("%s --version: %v\n%s", bin, err, out)
	}
	text := string(out)
	for _, line := range strings.Split(text, "\n") {
		trimmed := strings.TrimSpace(line)
		switch {
		case strings.HasPrefix(trimmed, "MPM ") && !strings.HasPrefix(trimmed, "MPM ·"):
			fields := strings.Fields(trimmed)
			if len(fields) >= 2 {
				version = fields[1]
			}
		case strings.HasPrefix(trimmed, "commit:"):
			commit = strings.TrimSpace(strings.TrimPrefix(trimmed, "commit:"))
		case strings.HasPrefix(trimmed, "dirty:"):
			dirty = strings.TrimSpace(strings.TrimPrefix(trimmed, "dirty:"))
		}
	}
	return version, commit, dirty
}

// TestD5_GitFreeBuildEmbedsTheAssertedIdentity is the D5 proof.
//
// Every one of the five binaries is built from a Git-free source tree
// and must report the revision the producer asserted.
func TestD5_GitFreeBuildEmbedsTheAssertedIdentity(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go toolchain not available")
	}

	tree := t.TempDir()
	gitFreeCopy(t, tree)
	binDir := buildFromGitFreeTree(t, tree, theCommit, "false")

	for _, name := range releaseBinaries {
		bin := filepath.Join(binDir, name)
		if _, err := os.Stat(bin); err != nil {
			t.Fatalf("%s was not built: %v", name, err)
		}
		version, commit, dirty := identityOf(t, bin)

		if commit != theCommit {
			t.Errorf("%s reports commit %q, want the asserted %q "+
				"(the identity was not embedded — it was resolved at run time, "+
				"or the producer's assertion was not honoured)", name, commit, theCommit)
		}
		if version == "" {
			t.Errorf("%s reports no product version", name)
		}
		if dirty != "no" && dirty != "false" {
			t.Errorf("%s reports dirty=%q, want the asserted clean state", name, dirty)
		}
	}
}

// TestD5_GitFreeBuildWithoutTheAssertionIsUnknown is the control.
//
// Without the producer's assertion, the same Git-free tree has no
// history to report, and the binaries say so.
//
// This is what makes the previous test meaningful: a binary that
// happened to be built elsewhere would also report a commit, and only
// this control proves the commit came from the assertion.
func TestD5_GitFreeBuildWithoutTheAssertionIsUnknown(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go toolchain not available")
	}

	tree := t.TempDir()
	gitFreeCopy(t, tree)

	// No MPM_BUILD_COMMIT: the tree has no history.
	prov := exec.Command(filepath.Join(tree, "scripts", "build-provenance.sh"), "commit")
	prov.Dir = tree
	out, err := prov.Output()
	if err != nil {
		t.Fatalf("build-provenance.sh: %v", err)
	}
	if got := strings.TrimSpace(string(out)); got != "unknown" {
		t.Fatalf("a Git-free tree without the producer's assertion must report "+
			"\"unknown\", got %q", got)
	}
}

// TestD5_VersionJSONCarriesTheEmbeddedIdentity proves the machine
// surface carries the same identity, from a Git-free build.
//
// The JSON form is what an operator's tooling reads, so an identity
// that is only in the human form would be a partial fix.
func TestD5_VersionJSONCarriesTheEmbeddedIdentity(t *testing.T) {
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go toolchain not available")
	}

	tree := t.TempDir()
	gitFreeCopy(t, tree)
	binDir := buildFromGitFreeTree(t, tree, theCommit, "false")

	bin := filepath.Join(binDir, "mpm")
	workspace := t.TempDir()
	cmd := exec.Command(bin, "version", "--json")
	cmd.Dir = workspace
	cmd.Env = append(os.Environ(),
		"MPM_WORKSPACE="+workspace,
		"HOME="+workspace,
	)
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("mpm version --json: %v", err)
	}
	var info versionInfo
	if err := json.Unmarshal(out, &info); err != nil {
		t.Fatalf("the Git-free binary did not emit valid JSON: %v\nraw=%s", err, string(out))
	}
	if info.Commit != theCommit {
		t.Errorf("the JSON identity reports commit %q, want %q", info.Commit, theCommit)
	}
	if info.DirtyState != "clean" {
		t.Errorf("the JSON identity reports dirty_state %q, want \"clean\"", info.DirtyState)
	}
}
