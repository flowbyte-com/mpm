#!/usr/bin/env python3
r"""
install_claude_instructions.py — Install Claude Code CLAUDE.md with MPM
behavioral protocol, idempotently.

Usage (called by install.sh):
    python3 install_claude_instructions.py \
        --scope user \                        # or 'project'
        --home "$HOME" \
        --target "$HOME/.claude/CLAUDE.md" \  # resolved by install.sh
        --snippet /path/to/CLAUDE.md.snippet

Behavior:
    - If target does not exist: create it with a header + the MPM snippet.
    - If target exists without the managed block: append the snippet after
      a clearly-marked comment.
    - If target exists WITH the managed block already (BEGIN/END markers
      found): no-op. Update via uninstall + reinstall if you want to
      refresh.
    - If target exists but legacy managed markers are present (single
      comment marker from a previous version): replace the legacy block
      with the new managed block, preserving all other content.
    - Backs up the existing target before any modification.

The script deliberately fails closed: if anything unexpected is in the
target file (e.g., partial markers), it aborts and asks the operator.

This script does NOT touch MPM core, MPM source, or any path outside
~/.claude (for user scope) or the project's CLAUDE.md (for project scope).
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path


# We recognize two forms:
#   - New:    <!-- BEGIN MPM-MANAGED SECTION:claude-code-instructions --> / matching END
#   - Legacy: <!-- BEGIN MPM-MANAGED SECTION -->  (any version without a colon-suffix)
# We do NOT match random `<-- BEGIN mpm-claude-code-managed -->` style markers
# from unrelated plugins because that would conflate their managed blocks with
# ours in a shared file.
# The trailing optional group `(?: [^\n]*)?` allows for a space-separated note
# after the marker (e.g., "<!-- BEGIN ... -->") AND a colon-suffix variant.
MANAGED_BEGIN_RE = re.compile(r"<!-- BEGIN MPM-MANAGED SECTION(?:[: ][^\n]*| [^\n]*)?-->")
MANAGED_END_RE   = re.compile(r"<!-- END MPM-MANAGED SECTION(?:[: ][^\n]*| [^\n]*)?-->")
LEGACY_BEGIN_RE  = re.compile(r"<!-- BEGIN MPM-MANAGED SECTION(?:[: ][^\n]*| [^\n]*)?-->")
LEGACY_END_RE    = re.compile(r"<!-- END MPM-MANAGED SECTION(?:[: ][^\n]*| [^\n]*)?-->")

# Outer managed-section markers (must match renderer's copy_paste_outer_*).
OUTER_BEGIN = "<!-- BEGIN MPM-MANAGED SECTION:claude-code-instructions -->"
OUTER_END   = "<!-- END MPM-MANAGED SECTION:claude-code-instructions -->"

HEAD_COMMENT = """\
<!--
This file's CLAUDE.md content is managed by the mpm-claude-code plugin's
install.sh. The block between BEGIN/END MPM-MANAGED SECTION markers is
regenerated by the installer; everything outside the markers is preserved.

To uninstall: re-run install.sh with --remove-managed-section.
-->"""


def footer() -> str:
    return OUTER_END


def build_managed_block(snippet_body: str) -> str:
    """Build the managed block to match the renderer's compose_snippet output
    exactly. The outer managed-section markers wrap the snippet body
    verbatim; the snippet itself already includes the inner
    <!-- BEGIN MPM MANAGED BLOCK --> / <!-- END MPM MANAGED BLOCK -->
    markers from the renderer's render_for_host.

    Earlier revisions of this function prepended a `<!-- generated: ... -->`
    timestamp and a `<!-- source: ... -->` line. Those were removed:
    they created a content-blinder where the installer's output never
    byte-matched the renderer's canonical output, so the
    check-installed-drift guard (3760e0e6) reported false-positive
    drift after every successful refresh. The body comparison below is
    the authoritative currency check: byte-equality between the
    extracted managed block and the rendered canonical block.
    """
    return f"{OUTER_BEGIN}\n{snippet_body.rstrip()}\n{OUTER_END}\n"


def install(scope: str, home: str, target: str, snippet_path: str) -> int:
    target_path = Path(target)
    snippet = Path(snippet_path).read_text()

    # Build the managed block from the canonical snippet. The result
    # is the same bytes the renderer (render_managed_blocks.py
    # compose_snippet) would produce today; the body comparison below
    # is therefore a byte-equality test against the canonical render
    # at the time of install.
    managed_block = build_managed_block(snippet)

    if not target_path.exists():
        # Fresh install: write header + managed block.
        target_path.parent.mkdir(parents=True, exist_ok=True)
        target_path.write_text(HEAD_COMMENT + "\n\n" + managed_block)
        print(f"[install_claude_instructions] wrote fresh {target_path}")
        return 0

    # Existing file: parse, decide, write.
    existing = target_path.read_text()

    if MANAGED_BEGIN_RE.search(existing) and MANAGED_END_RE.search(existing):
        # Already managed — compare the extracted block against the
        # canonical render. If they match byte-for-byte, no-op. If they
        # differ, replace. The body is the entire managed block
        # (BEGIN+body+END), so the comparison catches both content
        # drift and any structural divergence from the renderer.
        #
        # Normalize both sides to rstrip() before comparing: the regex
        # extraction does not include any trailing newline after the
        # END marker, and the canonical block has a trailing \n.
        # Without normalization, an otherwise-current file would
        # appear stale on every run (false-positive drift).
        new_managed = managed_block.rstrip()
        if (_extract_managed_block(existing) or "").rstrip() == new_managed:
            print(f"[install_claude_instructions] {target_path} already has current managed section; no-op")
            return 0
        backup = backup_path(target_path)
        shutil.copy2(target_path, backup)
        replaced = re.sub(
            MANAGED_BEGIN_RE.pattern + r".*?"+MANAGED_END_RE.pattern,
            new_managed,
            existing,
            flags=re.DOTALL,
        )
        target_path.write_text(replaced)
        print(
            f"[install_claude_instructions] {target_path} had stale managed "
            f"section — refreshed from snippet. backup at {backup}"
        )
        return 0

    if LEGACY_BEGIN_RE.search(existing) and LEGACY_END_RE.search(existing):
        # Legacy managed block from earlier plugin version — replace it with
        # the new format, preserving content outside the legacy markers.
        backup = backup_path(target_path)
        shutil.copy2(target_path, backup)
        legacy_block = extract_legacy_block(existing)
        if legacy_block is None:
            print(
                f"[install_claude_instructions] ERROR: could not extract legacy "
                f"managed block from {target_path}; refusing to overwrite. backup "
                f"is at {backup}.",
                file=sys.stderr,
            )
            return 2
        replacement = existing.replace(legacy_block, managed_block.rstrip() + "\n")
        target_path.write_text(replacement)
        print(
            f"[install_claude_instructions] {target_path} had legacy managed "
            f"block — replaced in-place. backup at {backup}"
        )
        return 0

    # BEGIN without a matching END — corrupted file. Abort safely.
    #
    # Conservative handling: an orphan END (no BEGIN) in user content
    # is unusual but not catastrophic. The append path below will add
    # the managed block at the end of the file, leaving the orphan in
    # place. A BEGIN-without-END is the structurally dangerous case:
    # the regex below would walk past the missing END and consume
    # arbitrary file content as if it were inside the managed block.
    if MANAGED_BEGIN_RE.search(existing) and not MANAGED_END_RE.search(existing):
        backup = backup_path(target_path)
        shutil.copy2(target_path, backup)
        print(
            f"[install_claude_instructions] ERROR: {target_path} has "
            f"a BEGIN marker without a matching END; refusing to modify. "
            f"backup at {backup}.",
            file=sys.stderr,
        )
        return 2

    # (Orphan END in user content is handled by the append path below
    # — the END stays in place and the new managed block is added at
    # the end. The structurally dangerous case, BEGIN-without-END, was
    # already caught above.)

    # No managed block present: back up and append.
    backup = backup_path(target_path)
    shutil.copy2(target_path, backup)
    insertion = "\n\n" + HEAD_COMMENT + "\n\n" + managed_block.rstrip() + "\n"
    target_path.write_text(existing.rstrip() + insertion)
    print(
        f"[install_claude_instructions] appended managed section to "
        f"{target_path}; backup at {backup}; scope={scope}"
    )
    return 0


def uninstall(target: str) -> int:
    target_path = Path(target)
    if not target_path.exists():
        print(f"[install_claude_instructions] no CLAUDE.md at {target_path}; nothing to uninstall")
        return 0
    existing = target_path.read_text()
    # Try the new managed form first, fall back to legacy.
    for begin_re, end_re, label in (
        (MANAGED_BEGIN_RE, MANAGED_END_RE, "managed"),
        (LEGACY_BEGIN_RE,  LEGACY_END_RE,  "legacy"),
    ):
        if begin_re.search(existing) and end_re.search(existing):
            backup = backup_path(target_path)
            shutil.copy2(target_path, backup)
            out = re.sub(
                begin_re.pattern + r".*?" + end_re.pattern,
                "",
                existing,
                flags=re.DOTALL,
            )
            # If only the head comment remains, delete the file entirely so the
            # user isn't left with a stub CLAUDE.md.
            if out.strip() == HEAD_COMMENT.strip() or out.strip() == "":
                target_path.unlink()
                print(
                    f"[install_claude_instructions] removed {label} section from "
                    f"{target_path} and unlinked the now-empty file; backup at {backup}"
                )
                return 0
            target_path.write_text(out)
            print(
                f"[install_claude_instructions] removed {label} section from "
                f"{target_path}; backup at {backup}"
            )
            return 0
    print(f"[install_claude_instructions] no managed section found at {target_path}")
    return 0


def backup_path(target_path: Path) -> Path:
    parent = target_path.parent
    name = target_path.name + ".bak"
    i = 1
    p = parent / name
    while p.exists():
        p = parent / f"{target_path.name}.bak.{i}"
        i += 1
    return p


def extract_legacy_block(content: str) -> str | None:
    m = re.search(
        LEGACY_BEGIN_RE.pattern + r".*?" + LEGACY_END_RE.pattern,
        content,
        flags=re.DOTALL,
    )
    return m.group(0) if m else None


def _extract_managed_block(content: str) -> str | None:
    """Return the raw managed block (BEGIN/END inclusive) or None."""
    m = re.search(
        MANAGED_BEGIN_RE.pattern + r".*?" + MANAGED_END_RE.pattern,
        content,
        flags=re.DOTALL,
    )
    return m.group(0) if m else None


def main() -> int:
    ap = argparse.ArgumentParser(description="Install Claude Code CLAUDE.md with MPM section, idempotently.")
    ap.add_argument("--scope", choices=("user", "project"), required=True)
    ap.add_argument("--home", required=True, help="User HOME for expansion")
    ap.add_argument("--target", required=True, help="Absolute path to CLAUDE.md")
    ap.add_argument("--snippet", required=True, help="Path to the CLAUDE.md.snippet")
    ap.add_argument("--uninstall", action="store_true", help="Remove the managed section instead")
    args = ap.parse_args()
    if args.uninstall:
        return uninstall(args.target)
    return install(args.scope, args.home, args.target, args.snippet)


if __name__ == "__main__":
    sys.exit(main())
